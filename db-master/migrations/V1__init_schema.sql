/* V1__init_schema.sql - Initial Schema for JavaSurveyApp */

-- Table to track schema versions
CREATE TABLE SCHEMA_VERSION (
    VERSION INTEGER PRIMARY KEY,
    DESCRIPTION VARCHAR(255),
    APPLIED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- USERS Table
CREATE TABLE USERS (
    USER_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(255) NOT NULL UNIQUE,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    IS_ADMIN SMALLINT DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- FORMS Table
CREATE TABLE FORMS (
    FORM_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_ID INTEGER NOT NULL,
    OWNER_NAME VARCHAR(255),
    TITLE VARCHAR(255) NOT NULL,
    DESCRIPTION BLOB SUB_TYPE TEXT,
    IS_PUBLISHED SMALLINT DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- QUESTIONS Table
CREATE TABLE QUESTIONS (
    QUESTION_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID INTEGER NOT NULL,
    TITLE VARCHAR(255) NOT NULL,
    QUESTION_TYPE VARCHAR(50),
    IS_REQUIRED SMALLINT DEFAULT 0,
    DESCRIPTION VARCHAR(2000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (FORM_ID) REFERENCES FORMS(FORM_ID) ON DELETE CASCADE
);

-- OPTIONS Table
CREATE TABLE OPTIONS (
    OPTION_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QUESTION_ID INTEGER NOT NULL,
    OPTION_TEXT VARCHAR(255) NOT NULL,
    IMAGE_PATH VARCHAR(255),
    FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(QUESTION_ID) ON DELETE CASCADE
);

-- QUESTION_SETTINGS Table
CREATE TABLE QUESTION_SETTINGS (
    QUESTION_ID INTEGER PRIMARY KEY,
    SCALE_MIN INTEGER,
    SCALE_MAX INTEGER,
    GRID_ROWS INTEGER,
    GRID_COLUMNS INTEGER,
    GRID_ROWS_TEXT BLOB SUB_TYPE TEXT,
    GRID_COLUMNS_TEXT BLOB SUB_TYPE TEXT,
    HAS_IMAGE SMALLINT DEFAULT 0,
    IMAGE_PATH VARCHAR(255),
    FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(QUESTION_ID) ON DELETE CASCADE
);

-- SURVEY_RESPONSES Table
CREATE TABLE SURVEY_RESPONSES (
    RESPONSE_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID INTEGER NOT NULL,
    USER_ID INTEGER,
    COMPLETED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (FORM_ID) REFERENCES FORMS(FORM_ID) ON DELETE CASCADE,
    FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

-- ANSWERS Table
CREATE TABLE ANSWERS (
    ANSWER_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RESPONSE_ID INTEGER NOT NULL,
    QUESTION_ID INTEGER NOT NULL,
    OPTION_ID INTEGER,
    ANSWER_TEXT BLOB SUB_TYPE TEXT,
    FOREIGN KEY (RESPONSE_ID) REFERENCES SURVEY_RESPONSES(RESPONSE_ID) ON DELETE CASCADE,
    FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS(QUESTION_ID)
);

-- SESSIONS Table
CREATE TABLE SESSIONS (
    SESSION_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID INTEGER NOT NULL,
    SESSION_TOKEN VARCHAR(255) NOT NULL UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    EXPIRES_AT TIMESTAMP,
    FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

INSERT INTO SCHEMA_VERSION (VERSION, DESCRIPTION) VALUES (1, 'Initial Schema');
